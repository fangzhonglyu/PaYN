#!/usr/bin/env python3
"""Stimulus and golden outputs for the FlexPosit core bench (tb/power_flexposit_core.sv).

Writes, into OUT_DIR:
  flexposit_stim.svh   sizes, operating point and absolute .mem paths (the bench includes it via +incdir+OUT_DIR)
  act.mem              FP8 E4M3 activation codes, index (t*N + i)*K + k  (t counts the warm-up tiles first)
  w.mem                SerialPosit weight codes (P bits, MSB streamed first), index (t*N + j)*K + k
  scale.mem            signed 5-bit column scales, index t*N + j
  expect.mem           FP16 outputs, index (t*N + i)*N + j, from model/flexposit_rtl_exact.py (bit-exact model)
  meta.json            the same parameters, for the flow scripts

Operands follow the FlexPosit repo's own array test (hardware/scripts/run_array_test.py): uniform random FP8
codes, uniform random non-NaR Posit(P, es) codes, column scales uniform in [-8, 7].

  python3 gen_stim.py OUT_DIR --n 8 --k 256 --p 4 --es 1 --tiles 4 --seed 1
"""
from __future__ import annotations

import argparse
import json
import random
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "model"))
import flexposit_rtl_exact as ref  # noqa: E402


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("out_dir", type=Path)
    ap.add_argument("--n", type=int, default=8)
    ap.add_argument("--k", type=int, default=256)
    ap.add_argument("--p", type=int, default=4)
    ap.add_argument("--es", type=int, default=1)
    ap.add_argument("--tiles", type=int, default=4)
    ap.add_argument("--seed", type=int, default=1)
    ap.add_argument("--warmup", type=int, default=1,
                    help="extra tiles run (and checked) before the SAIF window, to flush the resetless state")
    a = ap.parse_args()
    if not 4 <= a.p <= 8 or not 0 <= a.es <= 2:
        ap.error("P must be 4..8 and es 0..2 (the RTL's supported range)")
    if a.k < 1 or a.tiles < 1 or a.n < 2:
        ap.error("need K >= 1, tiles >= 1, N >= 2")

    rng = random.Random(a.seed * 1_000_003 + a.p * 101 + a.es * 7 + a.n)
    n, k, p, es, tiles, warm = a.n, a.k, a.p, a.es, a.tiles, a.warmup
    if warm < 0:
        ap.error("--warmup must be >= 0")
    nar = 1 << (p - 1)
    posit_codes = [c for c in range(1 << p) if c != nar]

    acts, weights, scales, expect = [], [], [], []
    table = ref.product_table(p, es)  # [256, 2^P] exhaustive product table (bit-exact RTL commit)
    for _ in range(warm + tiles):
        a_t = [[rng.randrange(256) for _ in range(k)] for _ in range(n)]
        w_t = [[rng.choice(posit_codes) for _ in range(k)] for _ in range(n)]
        s_t = [rng.randint(-8, 7) for _ in range(n)]
        for i in range(n):
            for j in range(n):
                prods = [ref.Product(zero=bool(table[a_t[i][kk], w_t[j][kk]]["zero"]),
                                     sign=int(table[a_t[i][kk], w_t[j][kk]]["sign"]),
                                     exp=int(table[a_t[i][kk], w_t[j][kk]]["exp"]),
                                     mag=int(table[a_t[i][kk], w_t[j][kk]]["mag"])) for kk in range(k)]
                expect.append(ref.pipeline_lane_fp16(prods, s_t[j]))
        acts += [x for row in a_t for x in row]
        weights += [ref.native_to_stream_code(c, p) for col in w_t for c in col]
        scales += s_t

    out = a.out_dir.resolve()
    out.mkdir(parents=True, exist_ok=True)

    def write(name: str, values: list[int], digits: int) -> Path:
        path = out / name
        path.write_text("".join(f"{v:0{digits}x}\n" for v in values), encoding="ascii")
        return path

    paths = {
        "ACT": write("act.mem", acts, 2),
        "W": write("w.mem", weights, 2),
        "SCALE": write("scale.mem", [s & 0x1F for s in scales], 2),
        "EXPECT": write("expect.mem", expect, 4),
    }
    useful = tiles * n * n * k   # measured tiles only (the warm-up tiles run before the window)
    svh = [
        "// Generated by designs/baselines/flexposit/tools/gen_stim.py -- do not edit.",
        f"`define FP_N {n}",
        f"`define FP_K {k}",
        f"`define FP_P {p}",
        f"`define FP_ES {es}",
        f"`define FP_TILES {tiles}",
        f"`define FP_WARMUP {warm}",
        f"`define FP_USEFUL_MACS {useful}",
    ] + [f'`define FP_{key}_MEM "{path}"' for key, path in paths.items()]
    (out / "flexposit_stim.svh").write_text("\n".join(svh) + "\n", encoding="ascii")
    meta = dict(n=n, k=k, p=p, es=es, tiles=tiles, warmup=warm, seed=a.seed, useful_macs=useful,
                peak_mac_per_cycle=n * n / p, files={key: str(v) for key, v in paths.items()})
    (out / "meta.json").write_text(json.dumps(meta, indent=2) + "\n", encoding="ascii")
    print(f"stimulus N={n} K={k} P={p} es={es} tiles={tiles} (+{warm} warm-up): {useful} useful MAC -> {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
